package com.gui;

// Exercício 08 - Casting
//
// Crie a classe Exercicio08. Converta automaticamente um int de valor 25 para double e exiba os dois.
public class Exercicio08 {
    public static void main(String[] args) {
        int numero = 25;

        double convertido = numero;
        System.out.println("Inteiro: " + numero);
        System.out.println("Double: " + convertido);
    }
}
