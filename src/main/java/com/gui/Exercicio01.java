package com.gui;

// Exercício 01 - Tipos de dados
//
// Crie a classe Exercicio01. Declare uma variável String para o nome de um aluno, int para a idade,
// double para a nota e boolean para informar se ele está matriculado. Exiba todos os valores.
public class Exercicio01 {
    public static void main(String[] args) {
        String nome = "Ana";
        int idade = 20;
        double nota = 8.5;
        boolean matriculado = true;
        System.out.println("Nome: " + nome);
        System.out.println("Idade: " + idade);
        System.out.println("Nota: " + nota);
        System.out.println("Matriculado: " + matriculado);
    }
}
