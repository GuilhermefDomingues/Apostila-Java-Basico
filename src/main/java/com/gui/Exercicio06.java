package com.gui;

// Exercício 06 - String + números
//
// Crie a classe Exercicio06. Declare dois int, 10 e 20. Mostre a diferença entre "Resultado: " + a + b
// e "Resultado: " + (a + b).
public class Exercicio06 {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println("Resultado: " + a + b);
        System.out.println("Resultado: " + (a + b));
    }
}
