package com.gui;

// Exercício 15 - for
//
// Crie a classe Exercicio15. Use for para imprimir os números de 1 a 10.
public class Exercicio15 {
    public static void main(String[] args) {

        for (int numero = 1; numero <= 10; numero++) {
            System.out.println(numero);
        }
    }
}
